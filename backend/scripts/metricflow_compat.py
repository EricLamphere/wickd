"""Regenerate app/semantic/compat_data.py from PyPI metadata.

Run at release time (see the `release` skill), from backend/:

    .venv/bin/python scripts/metricflow_compat.py

For every dbt-metricflow release line (latest patch per minor, 0.6+) it records the
dbt-core range, Python range, engine and license; it also records the latest patch of
every dbt-core minor from 1.7 on. Commit the regenerated file.
"""

import json
import re
import sys
import urllib.request
from pathlib import Path

from packaging.requirements import Requirement
from packaging.version import InvalidVersion, Version

OUT = Path(__file__).resolve().parents[1] / "app" / "semantic" / "compat_data.py"
OLDEST_DBT_METRICFLOW = Version("0.6.0")
OLDEST_DBT_CORE = Version("1.7.0")


def _json(url: str) -> dict:
    with urllib.request.urlopen(url, timeout=20) as resp:
        return json.load(resp)


def _stable(releases: dict) -> list[Version]:
    out = []
    for raw, files in releases.items():
        try:
            v = Version(raw)
        except InvalidVersion:
            continue
        if not v.is_prerelease and any(not f.get("yanked") for f in files):
            out.append(v)
    return sorted(out)


def _latest_per_minor(versions: list[Version]) -> dict[str, Version]:
    latest: dict[str, Version] = {}
    for v in versions:
        latest[f"{v.major}.{v.minor}"] = v
    return latest


def _python_range(spec: str | None) -> tuple[str, str | None]:
    """(min, max exclusive or None) from requires_python like '>=3.10,<3.15'."""
    low = re.search(r">=\s*(\d+\.\d+)", spec or "")
    high = re.search(r"<\s*(\d+\.\d+)", spec or "")
    return (low.group(1) if low else "3.8", high.group(1) if high else None)


def _license(info: dict) -> str:
    expr = info.get("license_expression") or info.get("license") or ""
    if expr and len(expr) < 40:
        return expr
    for c in info.get("classifiers") or []:
        if c.startswith("License ::"):
            return c.split("::")[-1].strip()
    return "unknown"


def main() -> int:
    mf = _json("https://pypi.org/pypi/dbt-metricflow/json")
    lines = []
    for minor, version in sorted(_latest_per_minor(_stable(mf["releases"])).items(), key=lambda kv: kv[1]):
        if version < OLDEST_DBT_METRICFLOW:
            continue
        info = _json(f"https://pypi.org/pypi/dbt-metricflow/{version}/json")["info"]
        core = engine = None
        for raw in info.get("requires_dist") or []:
            req = Requirement(raw)
            if req.marker is not None and "extra" in str(req.marker):
                continue
            if req.name == "dbt-core":
                core = str(req.specifier)
            elif req.name == "metricflow":
                engine = str(req.specifier)
        if core is None:
            continue
        py_min, py_max = _python_range(info.get("requires_python"))
        lines.append({
            "dbt_metricflow": str(version),
            "dbt_core": core,
            "python_min": py_min,
            "python_max_exclusive": py_max,
            "engine": engine or "",
            "license": _license(info),
        })

    core_versions = [v for v in _stable(_json("https://pypi.org/pypi/dbt-core/json")["releases"]) if v >= OLDEST_DBT_CORE]
    latest_core = {k: str(v) for k, v in _latest_per_minor(core_versions).items()}

    OUT.write_text(
        '"""GENERATED by scripts/metricflow_compat.py — do not edit by hand."""\n\n'
        f"DBT_METRICFLOW_RELEASES = {json.dumps(lines, indent=4)}\n\n"
        f"DBT_CORE_LATEST_PATCHES = {json.dumps(latest_core, indent=4)}\n"
    )
    print(f"wrote {OUT} ({len(lines)} dbt-metricflow lines, {len(latest_core)} dbt-core minors)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
