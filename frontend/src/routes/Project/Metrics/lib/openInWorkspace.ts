// "Open in Workspace": write MetricFlow's SQL to a new file under <workspace>/metrics/
// and have the SQL Workspace open it. Never overwrites an existing file.
import { ApiError, api } from '../../../../lib/api';
import { CONTENT_KEY, OPEN_KEY, TAB_KEY } from '../../Workspace/sessionKeys';

const MAX_NAME_ATTEMPTS = 50;

export function workspaceFileName(base: string, attempt: number): string {
  const slug = base.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 60) || 'metric_query';
  return `${slug}${attempt > 1 ? `_${attempt}` : ''}.sql`;
}

/** 409 = the name is taken; anything else (permissions, network) is a real failure. */
function isTaken(err: unknown): boolean {
  return err instanceof ApiError && err.status === 409;
}

async function ensureDir(projectId: number, parent: string, name: string): Promise<void> {
  try {
    await api.files.newFile(projectId, name, parent, true);
  } catch (err) {
    if (!isTaken(err)) throw err;
  }
}

/** The new file's project-relative path; the caller navigates to the Workspace. */
export async function writeWorkspaceSql(projectId: number, base: string, sql: string): Promise<string> {
  const { relative_path: workspace } = await api.workspace.getPath(projectId);
  const dir = `${workspace}/metrics`;
  await ensureDir(projectId, workspace, 'metrics');
  for (let attempt = 1; attempt <= MAX_NAME_ATTEMPTS; attempt++) {
    const name = workspaceFileName(base, attempt);
    try {
      await api.files.newFile(projectId, name, dir, false);
    } catch (err) {
      if (isTaken(err)) continue;
      throw err;
    }
    const path = `${dir}/${name}`;
    await api.files.putContent(projectId, path, `-- Generated by MetricFlow (wickd Metrics)\n${sql}\n`);
    try {
      sessionStorage.setItem(OPEN_KEY(projectId), path);
      sessionStorage.removeItem(CONTENT_KEY(projectId, path));
      sessionStorage.setItem(TAB_KEY(projectId), 'code');
    } catch {
      // storage unavailable: the Workspace just won't preselect the file
    }
    return path;
  }
  throw new Error(`Couldn't find a free file name in ${dir}`);
}
